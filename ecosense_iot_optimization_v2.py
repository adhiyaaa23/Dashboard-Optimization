def run_ecosense_pipeline(
    target_machine: str = "M01",
) -> dict:
    """
    Pipeline lengkap EcoSense v2.0:
    1.  IoT multi-mesin (7 hari, 6 fitur sensor)
    2.  Ensemble Energy Model (VotingRegressor + Permutation Importance)
    3.  Anomaly Ensemble (IForest + LOF + Z-Score + voting + F1 score)
    4.  Advanced SPC (X-bar + CUSUM + EWMA)
    5.  Multi-Objective Optimization (NSGA-II / Pareto front)
    6.  Stress Test (7 skenario + degradasi efisiensi)
    7.  Streaming Alert Engine (3 jenis alert real-time)
    8.  Unified Dashboard (12 panel)
    9.  JSON Export
    """
    print("=" * 65)
    print("  EcoSense v2.0 – IoT Energy Optimization Digital Twin")
    print("  AHM Manufacturing | Ensemble ML + NSGA-II + CUSUM/EWMA")
    print("=" * 65 + "\n")

    # 1. Simulasi data IoT
    print("📡 [1/7] Simulasi data IoT multi-mesin (7 hari, 6 sensor)...")
    df = generate_iot_sensor_data()

    # 2. Ensemble Energy Model
    print("🔬 [2/7] Membangun Ensemble Energy Model...")
    model_result = build_energy_model(df, machine_id=target_machine)

    # 3. Anomaly Detection Ensemble
    print("🔎 [3/7] Anomaly Detection Ensemble (IForest + LOF + Z-Score)...")
    anom_df, anom_summary = detect_sensor_anomalies(df, machine_id=target_machine)

    # 4. Advanced SPC
    print("📊 [4/7] Advanced SPC (X-bar + CUSUM + EWMA)...")
    energy_vals = df[df["machine_id"] == target_machine]["Y_energy_kWh"].values
    spc_result = calculate_control_limits(energy_vals)

    # 5. Multi-Objective Optimization
    print("🎯 [5/7] Multi-Objective Optimization (NSGA-II / Pareto)...")
    opt_result = optimize_machine_settings(model_result)

    # 6. Stress Test
    print("⚡ [6/7] Stress Test (7 skenario, termasuk degradasi efisiensi)...")
    stress_df = stress_test_simulation(model_result, production_increase_pct=20)

    # 7. Streaming Alert Engine
    print("📡 [7/7] Streaming Alert Engine (real-time simulation)...")
    alert_engine = simulate_streaming(df, spc_result, machine_id=target_machine)

    # Ringkasan
    print(f"{'═'*65}")
    print("  RINGKASAN EKSEKUTIF – EcoSense v2.0")
    print(f"{'═'*65}")
    print(f"  Target Mesin              : {target_machine}")
    print(f"  Ensemble Model (R²)       : {model_result['r2_test']:.4f}")
    print(f"  Anomali Ensemble (F1)     : {anom_summary['f1']:.3f}  "
          f"({anom_summary['count']} titik)")
    print(f"  CUSUM Out-of-Control      : {spc_result['cusum_ooc'].sum()} titik")
    print(f"  EWMA  Out-of-Control      : {spc_result['ewma_ooc'].sum()} titik")
    print(f"  Metode Optimasi           : {opt_result['method']}")
    print(f"  Pareto Solutions          : {len(opt_result['pareto_front'])}")
    print(f"  Penghematan Energi        : {opt_result['saving_pct']:.2f}%")
    print(f"  Estimasi Hemat Tahunan    : "
          f"Rp {opt_result['annual_saving_idr']/1e9:.3f} Miliar")
    print(f"  Streaming Alerts          : {alert_engine.get_summary()['total_alerts']}")
    print(f"{'═'*65}\n")

    # Dashboard
    print("📈 Membuat Dashboard (12 panel)...")
    visualize_digital_twin(
        df, anom_df, spc_result, model_result,
        opt_result, stress_df, machine_id=target_machine,
    )

    # Export JSON
    report_path = export_report(
        df, model_result, spc_result, opt_result,
        stress_df, anom_summary, alert_engine,
    )
    print(f"📁 Laporan JSON: {report_path}")
    print("✅ EcoSense v2.0 Pipeline selesai!")

    return {
        "df": df, "anom_df": anom_df,
        "model_result": model_result,
        "spc_result": spc_result,
        "opt_result": opt_result,
        "stress_df": stress_df,
        "anom_summary": anom_summary,
        "alert_engine": alert_engine,
    }


