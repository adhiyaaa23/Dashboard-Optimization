def detect_sensor_anomalies(
    df: pd.DataFrame,
    machine_id: str = "M01",
    contamination: float = CFG.anomaly_contamination,
) -> tuple[pd.DataFrame, dict]:
    """
    [UPGRADE v2] Ensemble 3 detektor dengan majority voting.
    - v1: hanya IsolationForest
    - v2: IsolationForest + LOF + Z-Score robust (MAD) → voting ≥ 2/3
    - Tambah fitur cross-variabel: load/temp ratio, energy/rpm ratio
    - Hitung Precision, Recall, F1 vs ground truth secara otomatis
    """
    mdf = df[df["machine_id"] == machine_id].copy().reset_index(drop=True)

    # Feature engineering temporal
    for col in ["X_Temp", "X_Load", "X_RPM", "Y_energy_kWh"]:
        mdf[f"{col}_diff"]   = mdf[col].diff().fillna(0)
        mdf[f"{col}_roll5"]  = mdf[col].rolling(5, min_periods=1).mean()
        mdf[f"{col}_roll_std"] = mdf[col].rolling(5, min_periods=1).std().fillna(0)
        mdf[f"{col}_ewm"]    = mdf[col].ewm(span=10).mean()

    mdf["load_temp_ratio"] = mdf["X_Load"] / (mdf["X_Temp"] + 1e-6)
    mdf["energy_per_rpm"]  = mdf["Y_energy_kWh"] / (mdf["X_RPM"] + 1e-6)

    feat_cols = (
        ["X_Temp", "X_Load", "X_RPM", "Y_energy_kWh",
         "X_Ambient_Temp", "X_Efficiency"]
        + [c for c in mdf.columns if any(s in c for s in
           ["_diff", "_roll5", "_roll_std", "_ewm", "ratio", "per_rpm"])]
    )
    feat_cols = [c for c in feat_cols if c in mdf.columns]
    X = mdf[feat_cols].fillna(0).values
    X_s = StandardScaler().fit_transform(X)

    # Detektor 1: Isolation Forest
    iforest = IsolationForest(n_estimators=300, contamination=contamination,
                               random_state=42, max_samples="auto")
    iforest_labels = iforest.fit_predict(X_s) == -1
    iforest_scores = -iforest.decision_function(X_s)

    # Detektor 2: Local Outlier Factor (baru)
    lof = LocalOutlierFactor(n_neighbors=20, contamination=contamination, novelty=False)
    lof_labels = lof.fit_predict(X_s) == -1
    lof_scores = -lof.negative_outlier_factor_

    # Detektor 3: Z-Score robust berbasis MAD (baru)
    energy = mdf["Y_energy_kWh"].values
    median_e = np.median(energy)
    mad_e    = np.median(np.abs(energy - median_e)) * 1.4826
    zscore_labels = np.abs(energy - median_e) > 3.5 * (mad_e + 1e-9)
    zscore_scores = np.abs(energy - median_e) / (mad_e + 1e-9)

    # Voting ≥ 2/3 → anomali
    votes = (iforest_labels.astype(int)
             + lof_labels.astype(int)
             + zscore_labels.astype(int))
    ensemble_labels = votes >= 2

    composite_score = (
        iforest_scores / (iforest_scores.max() + 1e-9)
        + lof_scores   / (lof_scores.max()    + 1e-9)
        + zscore_scores / (zscore_scores.max() + 1e-9)
    ) / 3.0

    mdf["anomaly_iforest"]  = iforest_labels
    mdf["anomaly_lof"]      = lof_labels
    mdf["anomaly_zscore"]   = zscore_labels
    mdf["anomaly_ensemble"] = ensemble_labels
    mdf["anomaly_score"]    = composite_score
    mdf["anomaly_votes"]    = votes

    # Precision / Recall / F1 vs ground truth
    true = mdf["is_anomaly_true"].values
    tp = int((ensemble_labels & true).sum())
    fp = int((ensemble_labels & ~true).sum())
    fn = int((~ensemble_labels & true).sum())
    precision = tp / (tp + fp + 1e-9)
    recall    = tp / (tp + fn + 1e-9)
    f1        = 2 * precision * recall / (precision + recall + 1e-9)

    print(f"🔎 [Anomaly Ensemble – {machine_id}]  "
          f"Terdeteksi: {ensemble_labels.sum()} ({ensemble_labels.mean()*100:.1f}%)")
    print(f"   IForest: {iforest_labels.sum()} | "
          f"LOF: {lof_labels.sum()} | Z-Score: {zscore_labels.sum()}")
    print(f"   Precision={precision:.3f} | Recall={recall:.3f} | F1={f1:.3f}\n")

    return mdf, {
        "count":     int(ensemble_labels.sum()),
        "rate":      float(ensemble_labels.mean()),
        "precision": precision,
        "recall":    recall,
        "f1":        f1,
    }


def detect_anomalies_realtime(energy_stream: np.ndarray, spc_result: dict) -> dict:
    """Deteksi anomali point-per-point menggunakan batas SPC."""
    upper = spc_result.get("robust_upper", spc_result["UCL_xbar"])
    lower = spc_result.get("robust_lower", spc_result["LCL_xbar"])
    anomalies = (energy_stream > upper) | (energy_stream < lower)
    return {
        "energy":        energy_stream,
        "anomalies":     anomalies,
        "upper_bound":   upper,
        "lower_bound":   lower,
        "anomaly_count": int(anomalies.sum()),
        "anomaly_rate":  float(anomalies.mean()),
    }


# ─────────────────────────────────────────────────────────────────
# MODUL 4: ADVANCED SPC – CUSUM + EWMA (UPGRADE)
# ─────────────────────────────────────────────────────────────────

def calculate_control_limits(
    data: np.ndarray,
    subgroup_size: int = CFG.spc_subgroup_size,
) -> dict:
    """
    [UPGRADE v2] Tambah CUSUM chart & EWMA chart di samping X-bar/S tradisional.
    - v1: hanya X-bar/S + robust MAD
    - v2: + CUSUM (deteksi pergeseran kecil persisten)
           + EWMA  (deteksi tren bertahap)
    """
    n = subgroup_size

    # Faktor c4 untuk estimasi sigma yang tidak bias
    c4_map = {2:0.7979, 3:0.8862, 4:0.9213, 5:0.9400,
              6:0.9515, 7:0.9594, 8:0.9650, 9:0.9693, 10:0.9727}
    c4 = c4_map.get(n, 0.9594)

    n_complete = (len(data) // n) * n
    subgroups = data[:n_complete].reshape(-1, n)
    xbar = subgroups.mean(axis=1)
    s    = subgroups.std(axis=1, ddof=1)
    xbar_bar = xbar.mean()
    s_bar    = s.mean()
    sigma_est = s_bar / c4

    A3 = 3 / (c4 * np.sqrt(n))
    UCL_xbar = xbar_bar + A3 * s_bar
    LCL_xbar = xbar_bar - A3 * s_bar

    # Robust bounds (MAD)
    med = np.median(data[:n_complete])
    mad = np.median(np.abs(data[:n_complete] - med)) * 1.4826
    robust_upper = med + 3 * mad
    robust_lower = med - 3 * mad
    ooc_xbar = (xbar > UCL_xbar) | (xbar < LCL_xbar)

    # === CUSUM Chart (baru) ===
    k = 0.5 * sigma_est   # reference value
    h = 5.0 * sigma_est   # decision interval
    cusum_pos = np.zeros(len(data))
    cusum_neg = np.zeros(len(data))
    for i in range(1, len(data)):
        cusum_pos[i] = max(0, cusum_pos[i-1] + (data[i] - xbar_bar) - k)
        cusum_neg[i] = max(0, cusum_neg[i-1] - (data[i] - xbar_bar) - k)
    cusum_ooc = (cusum_pos > h) | (cusum_neg > h)

    # === EWMA Chart (baru) ===
    lam = 0.2
    L   = 3.0
    ewma = np.zeros(len(data))
    ewma[0] = data[0]
    for i in range(1, len(data)):
        ewma[i] = lam * data[i] + (1 - lam) * ewma[i-1]
    ewma_sigma = sigma_est * np.sqrt(lam / (2 - lam))
    UCL_ewma = xbar_bar + L * ewma_sigma
    LCL_ewma = xbar_bar - L * ewma_sigma
    ewma_ooc = (ewma > UCL_ewma) | (ewma < LCL_ewma)

    print(f"📊 [Advanced SPC] n={n} per subgroup | σ_est={sigma_est:.3f}")
    print(f"   X-bar  UCL/LCL: {UCL_xbar:.3f} / {LCL_xbar:.3f}  "
          f"OOC: {ooc_xbar.sum()}/{len(xbar)}")
    print(f"   CUSUM  OOC: {cusum_ooc.sum()}/{len(data)}  "
          f"EWMA OOC: {ewma_ooc.sum()}/{len(data)}\n")

    return {
        "xbar": xbar, "s": s,
        "xbar_bar": xbar_bar, "s_bar": s_bar, "sigma_est": sigma_est,
        "UCL_xbar": UCL_xbar, "LCL_xbar": LCL_xbar,
        "ooc_xbar": ooc_xbar,
        "robust_upper": robust_upper, "robust_lower": robust_lower,
        "cusum_pos": cusum_pos, "cusum_neg": cusum_neg,
        "cusum_threshold": h, "cusum_ooc": cusum_ooc,
        "ewma": ewma,
        "UCL_ewma": UCL_ewma, "LCL_ewma": LCL_ewma, "ewma_ooc": ewma_ooc,
        "subgroup_size": n,
    }


