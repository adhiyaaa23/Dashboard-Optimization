# ─────────────────────────────────────────────────────────────────

class StreamingAlertEngine:
    """
    [BARU v2] Real-time alert engine dengan rolling window.
    3 jenis alert:
    1. SPC Violation  – titik melewati batas robust
    2. EWMA Trend     – EWMA melewati UCL/LCL
    3. Rate-of-Change – lonjakan tiba-tiba antar dua pembacaan
    """

    def __init__(self, spc_result: dict, window_size: int = 60):
        self.spc    = spc_result
        self.window = deque(maxlen=window_size)
        self.alerts: list[str] = []
        self.n_processed = 0

    def process_reading(
        self, energy_kwh: float, timestamp: str, machine_id: str
    ) -> list[str]:
        self.window.append(energy_kwh)
        self.n_processed += 1
        active: list[str] = []

        # Alert 1: SPC Violation
        if (energy_kwh > self.spc["robust_upper"]
                or energy_kwh < self.spc["robust_lower"]):
            active.append(
                f"🚨 SPC VIOLATION [{machine_id}] {timestamp}: "
                f"{energy_kwh:.3f} kWh  "
                f"(batas {self.spc['robust_lower']:.2f}–{self.spc['robust_upper']:.2f})"
            )

        # Alert 2: EWMA Trend
        if len(self.window) >= 5:
            recent = np.array(list(self.window)[-5:])
            ewma_val = float(recent[-1] * 0.2 + recent[:-1].mean() * 0.8)
            if ewma_val > self.spc["UCL_ewma"]:
                active.append(
                    f"📈 EWMA TREND UP [{machine_id}] {timestamp}: "
                    f"EWMA={ewma_val:.3f} > UCL={self.spc['UCL_ewma']:.3f}"
                )

        # Alert 3: Rapid Rate-of-Change
        if len(self.window) >= 2:
            roc = abs(list(self.window)[-1] - list(self.window)[-2])
            threshold = self.spc["sigma_est"] * 2.5
            if roc > threshold:
                active.append(
                    f"⚡ RAPID CHANGE [{machine_id}] {timestamp}: "
                    f"Δ={roc:.3f} kWh  (threshold={threshold:.3f})"
                )

        self.alerts.extend(active)
        return active

    def get_summary(self) -> dict:
        return {
            "total_processed": self.n_processed,
            "total_alerts":    len(self.alerts),
            "alert_rate":      len(self.alerts) / max(1, self.n_processed),
            "recent_alerts":   self.alerts[-5:],
        }


def simulate_streaming(
    df: pd.DataFrame,
    spc_result: dict,
    machine_id: str = "M01",
    n_stream: int = 300,
) -> StreamingAlertEngine:
    """Jalankan simulasi streaming real-time pada data terakhir."""
    mdf = df[df["machine_id"] == machine_id].tail(n_stream).reset_index(drop=True)
    engine = StreamingAlertEngine(spc_result)
    for _, row in mdf.iterrows():
        engine.process_reading(
            row["Y_energy_kWh"], str(row["timestamp"]), machine_id
        )
    s = engine.get_summary()
    print(f"📡 [Streaming Engine] Diproses: {s['total_processed']} pembacaan")
    print(f"   Total alert: {s['total_alerts']} (rate: {s['alert_rate']*100:.1f}%)")
    if s["recent_alerts"]:
        for a in s["recent_alerts"][-3:]:
            print(f"   {a}")
    print()
    return engine


