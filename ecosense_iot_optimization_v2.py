def stress_test_simulation(
    model_result: dict,
    production_increase_pct: int = 20,
) -> pd.DataFrame:
    """Proyeksi kebutuhan energi saat produksi naik X%."""
    print(f"⚡ [Stress Test] Simulasi kenaikan produksi +{production_increase_pct}%")
    scenarios = [0, 10, 20, 30, 50, 75, 100]
    baseline = {"X_Temp": 70.0, "X_Load": 70.0, "X_RPM": 1400.0,
                "X_Ambient_Temp": 30.0, "X_Humidity": 70.0, "X_Efficiency": 0.97}
    results = []
    for inc in scenarios:
        factor = 1 + inc / 100
        fv = {
            "X_Temp":         min(baseline["X_Temp"] + inc * 0.25, 110),
            "X_Load":         min(baseline["X_Load"]  * factor, 100),
            "X_RPM":          min(baseline["X_RPM"]   * factor, 2400),
            "X_Ambient_Temp": baseline["X_Ambient_Temp"],
            "X_Humidity":     baseline["X_Humidity"],
            "X_Efficiency":   max(0.88, baseline["X_Efficiency"] - inc * 0.001),
        }
        energy = predict_energy(model_result, fv)
        results.append({
            "Kenaikan Produksi (%)": inc,
            "Suhu (°C)":   round(fv["X_Temp"], 1),
            "Beban (%)":   round(fv["X_Load"],  1),
            "RPM":         round(fv["X_RPM"],   1),
            "Efisiensi":   round(fv["X_Efficiency"], 3),
            "Energi (kWh)": round(energy, 3),
        })

    df_stress = pd.DataFrame(results)
    base_e = df_stress.iloc[0]["Energi (kWh)"]
    df_stress["Delta Energi (kWh)"] = (df_stress["Energi (kWh)"] - base_e).round(3)
    df_stress["Delta Energi (%)"]   = ((df_stress["Delta Energi (kWh)"] / base_e) * 100).round(2)
    print(df_stress.to_string(index=False))
    print()
    return df_stress


