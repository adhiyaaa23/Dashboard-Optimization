def build_energy_model(
    df: pd.DataFrame,
    machine_id: str = "M01",
    test_split: float = 0.2,
) -> dict:
    """
    [UPGRADE v2] VotingRegressor: Ridge + RandomForest + HGB.
    - v1 menggunakan seleksi model tunggal terbaik
    - v2 menggabungkan ketiganya via ensemble voting
    - Tambah Permutation Importance (XAI proxy) menggantikan coef_ sederhana
    - Fitur diperluas dari 3 → 6 variabel
    """
    mdf = df[df["machine_id"] == machine_id].copy().reset_index(drop=True)

    features = ["X_Temp", "X_Load", "X_RPM",
                "X_Ambient_Temp", "X_Humidity", "X_Efficiency"]
    target = "Y_energy_kWh"

    X = mdf[features].values
    y = mdf[target].values

    split_idx = int(len(X) * (1 - test_split))
    X_train, X_test = X[:split_idx], X[split_idx:]
    y_train, y_test = y[:split_idx], y[split_idx:]

    scaler = Pipeline([
        ("std", StandardScaler()),
        ("pwr", PowerTransformer(method="yeo-johnson", standardize=True)),
    ])
    X_tr_s = scaler.fit_transform(X_train)
    X_te_s = scaler.transform(X_test)

    # Sub-models
    ridge = RidgeCV(alphas=[0.01, 0.1, 1, 10, 100], cv=TimeSeriesSplit(n_splits=5))
    rf    = RandomForestRegressor(n_estimators=200, max_depth=10,
                                  min_samples_leaf=5, random_state=42, n_jobs=None)
    hgb   = HistGradientBoostingRegressor(max_iter=400, learning_rate=0.05,
                                          max_leaf_nodes=31, l2_regularization=0.1, random_state=42)

    # VotingRegressor ensemble
    ensemble = VotingRegressor(
        estimators=[("ridge", ridge), ("rf", rf), ("hgb", hgb)],
        n_jobs=None,
    )
    ensemble.fit(X_tr_s, y_train)

    y_pred = ensemble.predict(X_te_s)
    r2   = r2_score(y_test, y_pred)
    mae  = mean_absolute_error(y_test, y_pred)
    rmse = float(np.sqrt(np.mean((y_test - y_pred) ** 2)))

    # Permutation Importance (baru – menggantikan coef_ sederhana)
    perm = permutation_importance(ensemble, X_te_s, y_test,
                                  n_repeats=10, random_state=42, n_jobs=-1)
    importance = {
        feat: float(imp)
        for feat, imp in zip(features, perm.importances_mean)
    }

    residuals = y_test - y_pred

    print(f"🔬 [Ensemble Model – {machine_id}] "
          f"R²={r2:.4f} | MAE={mae:.4f} | RMSE={rmse:.4f}")
    print("   Permutation Importance:")
    for k, v in sorted(importance.items(), key=lambda x: -abs(x[1])):
        bar = "█" * int(max(0, v) * 250)
        print(f"   {k:<22}: {v:+.4f}  {bar}")
    print()

    return {
        "model":         ensemble,
        "scaler":        scaler,
        "features":      features,
        "r2_test":       r2,
        "mae_test":      mae,
        "rmse_test":     rmse,
        "y_pred_test":   y_pred,
        "y_test":        y_test,
        "residuals":     residuals,
        "importance":    importance,
        "machine_id":    machine_id,
    }


def predict_energy(model_result: dict, feature_values: dict) -> float:
    """Prediksi konsumsi energi untuk satu kondisi mesin."""
    feats = model_result["features"]
    X = np.array([[feature_values.get(f, 0.0) for f in feats]])
    X_s = model_result["scaler"].transform(X)
    return float(max(0, model_result["model"].predict(X_s)[0]))


