def optimize_machine_settings(
    model_result: dict,
    temp_bounds: tuple = (55, 90),
    load_bounds: tuple = (50, 95),
    rpm_bounds:  tuple = (1000, 1900),
    n_gen:  int = 80,
    pop_size: int = 100,
) -> dict:
    """
    [UPGRADE v2] Multi-objective optimization dengan NSGA-II (via DEAP).
    - v1: single-objective trust-constr (minimize energi saja)
    - v2: dua objective: minimize energi + maximize production_proxy
          → menghasilkan Pareto front, bukan satu titik optimal saja

    Fallback ke grid Pareto jika DEAP tidak terinstall.

    Install: pip install deap
    """
    try:
        from deap import base, creator, tools, algorithms
        has_deap = True
    except ImportError:
        has_deap = False

    def energy_fn(temp, load, rpm):
        return predict_energy(model_result, {
            "X_Temp": temp, "X_Load": load, "X_RPM": rpm,
            "X_Ambient_Temp": 30.0, "X_Humidity": 70.0, "X_Efficiency": 0.97,
        })

    def production_proxy(load, rpm):
        return load * rpm / 1e5  # production index

    baseline_energy = energy_fn(72.0, 75.0, 1500.0)

    if has_deap:
        # ─── NSGA-II ───
        try:
            creator.create("FitnessMulti2", base.Fitness, weights=(-1.0, +1.0))
            creator.create("Individual2", list, fitness=creator.FitnessMulti2)
        except Exception:
            pass

        toolbox = base.Toolbox()
        toolbox.register("attr_temp", np.random.uniform, *temp_bounds)
        toolbox.register("attr_load", np.random.uniform, *load_bounds)
        toolbox.register("attr_rpm",  np.random.uniform, *rpm_bounds)
        toolbox.register("individual", tools.initCycle, creator.Individual2,
                         (toolbox.attr_temp, toolbox.attr_load, toolbox.attr_rpm), n=1)
        toolbox.register("population", tools.initRepeat, list, toolbox.individual)

        def evaluate(ind):
            t = np.clip(ind[0], *temp_bounds)
            l = np.clip(ind[1], *load_bounds)
            r = np.clip(ind[2], *rpm_bounds)
            return energy_fn(t, l, r), production_proxy(l, r)

        toolbox.register("evaluate", evaluate)
        toolbox.register("mate",   tools.cxSimulatedBinaryBounded,
                         low=[temp_bounds[0], load_bounds[0], rpm_bounds[0]],
                         up= [temp_bounds[1], load_bounds[1], rpm_bounds[1]], eta=20.0)
        toolbox.register("mutate", tools.mutPolynomialBounded,
                         low=[temp_bounds[0], load_bounds[0], rpm_bounds[0]],
                         up= [temp_bounds[1], load_bounds[1], rpm_bounds[1]],
                         eta=20.0, indpb=0.3)
        toolbox.register("select", tools.selNSGA2)

        pop = toolbox.population(n=pop_size)
        algorithms.eaMuPlusLambda(pop, toolbox, mu=pop_size, lambda_=pop_size,
                                   cxpb=0.7, mutpb=0.3, ngen=n_gen,
                                   stats=None, halloffame=None, verbose=False)
        pareto = tools.sortNondominated(pop, len(pop), first_front_only=True)[0]
        pareto_data = [(ind[0], ind[1], ind[2],
                        ind.fitness.values[0], ind.fitness.values[1])
                       for ind in pareto]
        method = "NSGA-II (DEAP)"

    else:
        # ─── Fallback: Grid Pareto ───
        pts = 1000
        temps = np.random.uniform(*temp_bounds, pts)
        loads = np.random.uniform(*load_bounds, pts)
        rpms  = np.random.uniform(*rpm_bounds,  pts)
        all_pts = [(t, l, r, energy_fn(t, l, r), production_proxy(l, r))
                   for t, l, r in zip(temps, loads, rpms)]
        all_pts.sort(key=lambda x: x[3])
        pareto_data, best_p = [], -np.inf
        for pt in all_pts:
            if pt[4] > best_p:
                pareto_data.append(pt)
                best_p = pt[4]
        method = "Grid Pareto (install DEAP untuk NSGA-II: pip install deap)"

    # Pilih titik terbaik: energi terendah dengan produksi ≥ 90% maks
    prod_max = max(p[4] for p in pareto_data)
    valid = [p for p in pareto_data if p[4] >= prod_max * 0.90]
    best  = min(valid or pareto_data, key=lambda x: x[3])

    saving_kwh   = baseline_energy - best[3]
    saving_pct   = saving_kwh / baseline_energy * 100
    annual_kwh   = saving_kwh * CFG.annual_hours
    annual_idr   = annual_kwh * CFG.energy_tariff_idr

    print(f"🎯 [Multi-Obj Optimization] {method}")
    print(f"   Pareto front : {len(pareto_data)} solusi")
    print(f"   Baseline     : {baseline_energy:.3f} kWh")
    print(f"   Optimal      : {best[3]:.3f} kWh  → Hemat {saving_pct:.2f}%")
    print(f"   Hemat tahunan: Rp {annual_idr/1e9:.3f} Miliar\n")

    return {
        "method":             method,
        "pareto_front":       pareto_data,
        "best_point":         {"temp": best[0], "load": best[1], "rpm": best[2],
                               "energy": best[3], "production_index": best[4]},
        "baseline_energy":    baseline_energy,
        "saving_kwh":         saving_kwh,
        "saving_pct":         saving_pct,
        "annual_saving_kwh":  annual_kwh,
        "annual_saving_idr":  annual_idr,
        "current": {"temp": 72.0, "load": 75.0, "rpm": 1500.0, "energy": baseline_energy},
    }


