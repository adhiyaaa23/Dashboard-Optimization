def generate_iot_sensor_data(
    n_samples: int = CFG.n_samples,
    interval_seconds: int = CFG.interval_sec,
    n_machines: int = CFG.n_machines,
    seed: int = 42,
) -> pd.DataFrame:
    """
    [UPGRADE v2] Mensimulasikan data IoT multi-mesin selama 7 hari.

    Variabel Sensor (diperluas dari v1):
    - X_Temp           : Suhu operasional mesin (°C)
    - X_Load           : Beban mesin (% kapasitas)
    - X_RPM            : Kecepatan rotasi (RPM)
    - X_Ambient_Temp   : [BARU] Suhu lingkungan pabrik (°C)
    - X_Humidity       : [BARU] Kelembaban udara (%)
    - X_Efficiency     : [BARU] Efisiensi mesin (degradasi bertahap)
    - Y_energy_kWh     : Konsumsi energi aktual

    Pola Simulasi (diperluas dari v1):
    - 3 shift 8-jam (bukan 2 shift seperti v1)
    - Weekend: produksi 50% (baru)
    - Degradasi efisiensi mesin + recovery setelah maintenance (baru)
    - 3 tipe anomali: spike, drop, drift bertahap (v1 hanya spike/drop)
    """
    np.random.seed(seed)
    n = n_samples

    timestamps = pd.date_range(
        start="2024-01-08 00:00:00", periods=n, freq=f"{interval_seconds}s"
    )
    hours = np.array([t.hour + t.minute / 60 for t in timestamps])
    days  = np.array([t.dayofweek for t in timestamps])

    all_records = []

    for machine_id in range(1, n_machines + 1):
        np.random.seed(seed + machine_id * 100)

        # --- Variabel Lingkungan (baru) ---
        ambient_temp = (28 + 6 * np.sin(2 * np.pi * hours / 24 - np.pi)
                        + np.random.normal(0, 0.8, n))
        humidity = (65 + 15 * np.sin(2 * np.pi * hours / 24)
                    + np.random.normal(0, 3, n))
        ambient_temp = np.clip(ambient_temp, 20, 42)
        humidity     = np.clip(humidity, 40, 95)

        # --- Pola 3 Shift Realistis (upgrade dari 2 shift) ---
        def shift_load(h):
            if   6 <= h < 14: return 75   # Shift 1: pagi
            elif 14 <= h < 22: return 88  # Shift 2: siang (paling sibuk)
            else:               return 45 # Shift 3: malam (maintenance parsial)

        base_load      = np.vectorize(shift_load)(hours)
        weekend_factor = np.where(days >= 5, 0.5, 1.0)       # Weekend 50%
        machine_factor = 1.0 + (machine_id - 1) * 0.08       # M2/M3 sedikit lebih berat

        X_Load = (base_load * weekend_factor * machine_factor
                  + np.random.normal(0, 4, n))
        X_Load = np.clip(X_Load, 20, 100)

        # --- Suhu Mesin (terpengaruh beban + ambient) ---
        X_Temp = (55 + 0.3 * X_Load + 0.4 * (ambient_temp - 28)
                  + 8 * np.sin(2 * np.pi * hours / 16)
                  + np.random.normal(0, 2, n))
        X_Temp = np.clip(X_Temp, 45, 115)

        # --- RPM ---
        X_RPM = 1100 + 10 * X_Load + np.random.normal(0, 40, n)
        X_RPM = np.clip(X_RPM, 700, 2400)

        # --- Efisiensi Mesin (degradasi + recovery maintenance – baru) ---
        efficiency = 1.0 - (np.arange(n) / n) * 0.04
        efficiency[int(n * 0.72):] += 0.025  # recovery setelah maintenance
        efficiency = np.clip(efficiency, 0.92, 1.02)

        # --- Model Konsumsi Energi (diperluas dari v1) ---
        beta = [9.8, 0.09, 0.38, 0.0045, 0.015, -0.08]
        noise = np.random.normal(0, 1.2, n)
        Y = (beta[0]
             + beta[1] * X_Temp
             + beta[2] * X_Load
             + beta[3] * X_RPM
             + beta[4] * ambient_temp
             + beta[5] * humidity / 100
             + noise) / efficiency

        # --- Anomali: 3 tipe (upgrade dari 2 tipe di v1) ---
        n_anom = int(0.04 * n)
        anom_idx = np.random.choice(n, size=n_anom, replace=False)
        anom_labels = np.zeros(n, dtype=bool)
        anom_types = np.random.choice(
            ["spike", "drop", "drift"], size=n_anom, p=[0.5, 0.3, 0.2]
        )
        for idx, atype in zip(anom_idx, anom_types):
            if atype == "spike":
                Y[idx] *= np.random.uniform(1.5, 2.0)
            elif atype == "drop":
                Y[idx] *= np.random.uniform(0.3, 0.55)
            else:  # drift: 5 titik bertahap
                end = min(idx + 5, n)
                Y[idx:end] += np.linspace(3, 8, end - idx)
            anom_labels[idx] = True

        for i in range(n):
            all_records.append({
                "timestamp":      timestamps[i],
                "machine_id":     f"M{machine_id:02d}",
                "X_Temp":         round(float(X_Temp[i]), 2),
                "X_Load":         round(float(X_Load[i]), 2),
                "X_RPM":          round(float(X_RPM[i]), 1),
                "X_Ambient_Temp": round(float(ambient_temp[i]), 2),
                "X_Humidity":     round(float(humidity[i]), 2),
                "X_Efficiency":   round(float(efficiency[i]), 4),
                "Y_energy_kWh":   round(float(max(0, Y[i])), 3),
                "is_anomaly_true": bool(anom_labels[i]),
                "shift":          int(1 if 6 <= hours[i] < 14
                                     else 2 if 14 <= hours[i] < 22 else 3),
                "is_weekend":     bool(days[i] >= 5),
            })

    df = pd.DataFrame(all_records)
    total_anom = df["is_anomaly_true"].sum()
    print("✅ Dataset IoT Sensor Multi-Mesin berhasil dibuat.")
    print(f"   Total data points : {len(df):,} ({n_machines} mesin × {n_samples} sampel)")
    print(f"   Durasi            : {n_samples * interval_seconds / 3600:.1f} jam (7 hari)")
    print(f"   Anomali injeksi   : {total_anom} ({total_anom/len(df)*100:.1f}%)")
    print(f"   Fitur sensor      : 6 variabel (v1: 3 variabel)\n")
    return df


def summarize_data_health(df: pd.DataFrame) -> pd.DataFrame:
    """Ringkasan kualitas data IoT per mesin."""
    cols = ["X_Temp", "X_Load", "X_RPM", "X_Ambient_Temp", "X_Humidity", "Y_energy_kWh"]
    rows = []
    for mid in df["machine_id"].unique():
        mdf = df[df["machine_id"] == mid]
        for col in cols:
            row = mdf[col].describe().to_dict()
            row["machine_id"] = mid
            row["column"] = col
            row["missing_pct"] = mdf[col].isna().mean() * 100
            rows.append(row)
    return pd.DataFrame(rows)


